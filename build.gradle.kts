import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    `java-library`
    `maven-publish`
    idea
    id("net.neoforged.moddev") version "2.0.148"
    kotlin("jvm") version "2.4.0"
}

val mod_id: String by project
val mod_version: String by project
val mod_group_id: String by project
val neo_version: String by project
val parchment_minecraft_version: String by project
val parchment_mappings_version: String by project
val kff_version: String by project

tasks.named<Wrapper>("wrapper") {
    distributionType = Wrapper.DistributionType.BIN
}

version = mod_version
group = mod_group_id

base {
    archivesName = mod_id
}

// Mojang ships Java 21 to end users in 1.21.1, so mods should target Java 21.
java.toolchain.languageVersion = JavaLanguageVersion.of(21)

kotlin {
    jvmToolchain(21)
    compilerOptions {
        jvmTarget = JvmTarget.JVM_21
    }
}

sourceSets.main {
    resources {
        // Include resources generated by data generators.
        srcDir("src/generated/resources")
        // Exclude common development only resources from finalized outputs
        exclude("**/*.bbmodel")
        exclude("src/generated/**/.cache")
    }
}

repositories {
    maven("https://thedarkcolour.github.io/KotlinForForge/") {
        name = "Kotlin for Forge"
        content { includeGroup("thedarkcolour") }
    }
    maven("https://api.modrinth.com/maven") {
        name = "Modrinth"

    }
}

neoForge {
    version = neo_version

    parchment {
        mappingsVersion = parchment_mappings_version
        minecraftVersion = parchment_minecraft_version
    }

    runs {
        register("client") {
            client()
            systemProperty("neoforge.enabledGameTestNamespaces", mod_id)
        }

        register("server") {
            server()
            programArgument("--nogui")
            systemProperty("neoforge.enabledGameTestNamespaces", mod_id)
        }

        // Launches GameTestServer, runs all registered gametests, then exits.
        register("gameTestServer") {
            type = "gameTestServer"
            systemProperty("neoforge.enabledGameTestNamespaces", mod_id)
        }

        register("data") {
            data()
            programArguments.addAll(
                "--mod", mod_id,
                "--all",
                "--output", file("src/generated/resources/").absolutePath,
                "--existing", file("src/main/resources/").absolutePath,
            )
        }

        configureEach {
            systemProperty("forge.logging.markers", "REGISTRIES")
            logLevel = org.slf4j.event.Level.DEBUG
        }
    }

    mods {
        register(mod_id) {
            sourceSet(sourceSets.main.get())
        }
    }
}

// Asset generator: the race models, animations and placeholder textures are built by code in src/assetgen
// (Kotlin, no mod dependencies). Run `./gradlew generateAssets` after changing it; output goes into src/main.
val assetgen: SourceSet by sourceSets.creating

tasks.register<JavaExec>("generateAssets") {
    group = "rejecthumanity"
    description = "Regenerates race models, animations and placeholder textures from src/assetgen."
    classpath = assetgen.runtimeClasspath
    mainClass = "net.oraclehisty.rejecthumanity.assetgen.AssetGenKt"
    args(layout.projectDirectory.dir("src/main/resources/assets/$mod_id").asFile.absolutePath)
}

// Dependencies present for runtime testing but not pulled by dependents of this mod.
val localRuntime: Configuration by configurations.creating
configurations.runtimeClasspath {
    extendsFrom(localRuntime)
}

dependencies {
    // Kotlin language provider + Kotlin stdlib/reflect/coroutines/serialization at runtime.
    implementation("thedarkcolour:kotlinforforge-neoforge:$kff_version")
    implementation("maven.modrinth:8BmcQJ2H:Grwn5rUB")
}

// Expands ${} properties in src/main/templates (e.g. neoforge.mods.toml).
val generateModMetadata = tasks.register<ProcessResources>("generateModMetadata") {
    val replaceProperties = listOf(
        "minecraft_version", "minecraft_version_range", "neo_version", "loader_version_range",
        "kff_loader_version_range", "mod_id", "mod_name", "mod_license", "mod_version",
        "mod_authors", "mod_description",
    ).associateWith { project.property(it).toString() }
    inputs.properties(replaceProperties)
    expand(replaceProperties)
    from("src/main/templates")
    into("build/generated/sources/modMetadata")
}
sourceSets.main.get().resources.srcDir(generateModMetadata)
neoForge.ideSyncTask(generateModMetadata)

publishing {
    publications {
        register<MavenPublication>("mavenJava") {
            from(components["java"])
        }
    }
    repositories {
        maven("file://${project.projectDir}/repo")
    }
}

tasks.withType<JavaCompile>().configureEach {
    options.encoding = "UTF-8"
}

idea {
    module {
        isDownloadSources = true
        isDownloadJavadoc = true
    }
}
